const fs=require('fs'),os=require('os'),path=require('path');
const {createWhiteboard,safeName,extractText,MIN_SOURCE_CHARS}=require('../jsons/whiteboard/index.js');
let pass=0,fail=0;
const check=(ok,m,got)=>{ console.log((ok?'  [PASS] ':'  [FAIL] ')+m+(ok?'':'  got: '+JSON.stringify(got))); ok?pass++:fail++; };
(async () => {
  const ROOT=fs.mkdtempSync(path.join(os.tmpdir(),'wb-'));
  let outlineCalls=0, lastPrompt='';
  const wb=createWhiteboard({ getDir:()=>ROOT, generateOutline:async({prompt})=>{ outlineCalls++; lastPrompt=prompt; return {success:true, outline:'<div>OUTLINE</div>', docxPath:'X.docx'}; } });
  const scene={ elements:[ {id:'a',type:'text',text:'Ademption'}, {id:'b',type:'text',text:'Abatement'}, {id:'c',type:'rectangle'}, {id:'d',type:'arrow'}, {id:'e',type:'text',text:'   '} ], appState:{ viewBackgroundColor:'#fff', openDialog:null, scrollX:999 } };
  const png='data:image/png;base64,'+Buffer.from('fakepngbytes').toString('base64');
  const s=wb.save({ title:'Wills / Trusts .. probs', scene, pngBase64:png });
  check(s.success===true,'save() succeeded',s);
  check(fs.existsSync(s.jsonPath)&&fs.existsSync(s.pngPath)&&fs.existsSync(s.mdPath),'all three files written (.excalidraw + .png + .md)',[fs.existsSync(s.jsonPath),fs.existsSync(s.pngPath),fs.existsSync(s.mdPath)]);
  check(path.dirname(s.jsonPath)===ROOT,'landed INSIDE the root (title could not traverse out)',path.dirname(s.jsonPath));
  const raw=JSON.parse(fs.readFileSync(s.jsonPath,'utf8'));
  check(Array.isArray(raw.elements)&&raw.elements.length===5,'scene elements preserved verbatim (all 5)',raw.elements.length);
  check(!('openDialog' in raw.appState)&&!('scrollX' in raw.appState),'transient appState dropped from the file',Object.keys(raw.appState));
  const md=fs.readFileSync(s.mdPath,'utf8');
  check(md.includes('Ademption')&&md.includes('Abatement'),'.md carries text-tool labels verbatim',md.slice(0,70));
  check(extractText(scene).length===2,'extractText: 2 items, blank text ignored',extractText(scene).length);
  const l=wb.load({file:s.file});
  const lc=JSON.stringify((l.scene.elements||[]).map(e=>e.text||e.type));
  const oc=JSON.stringify(scene.elements.map(e=>e.text||e.type));
  check(l.success===true,'load() succeeded',l.error);
  check(lc===oc,'*** scene ROUND-TRIPS identically (write/read contract) ***',lc);
  check(!!l.pngDataUrl&&l.pngDataUrl.indexOf('data:image/png;base64,')===0,'png returns as a data URL',String(l.pngDataUrl).slice(0,26));
  const OUTSIDE=fs.mkdtempSync(path.join(os.tmpdir(),'wb-out-')); fs.writeFileSync(path.join(OUTSIDE,'secret.excalidraw'),'{"elements":[]}','utf8'); let escaped=false; try { const x=wb.load({file:path.join(OUTSIDE,'secret.excalidraw')}); escaped=!!(x&&x.success); } catch(e){ escaped=false; }
  check(escaped===false,'a file OUTSIDE the root cannot be loaded (traversal neutralised)',escaped);
  const L=wb.list();
  check(L.length===1&&L[0].hasPng&&L[0].hasMd,'list() reports the sketch with its companions',L.length);
  check(L[0].title.indexOf('Wills')===0,'list() strips the timestamp prefix for display',L[0].title);
  const short=await wb.convert({text:'too short',title:'t'});
  check(short.success===false&&short.reason==='too_short','convert() refuses under the floor',short.reason);
  check(outlineCalls===0,'*** and made NO model call under the floor ***',outlineCalls);
  const long='Duty of care. Breach. Proximate cause. Damages. Palsgraf. Comparative negligence under 768.81.';
  const c=await wb.convert({text:long,title:'Torts'});
  check(c.success===true,'convert() succeeded over the floor',c);
  check(outlineCalls===1,'exactly one model call',outlineCalls);
  check(lastPrompt.indexOf('Do not add doctrinal content not present in the source')!==-1,'prompt carries the no-invention gate',true);
  check(lastPrompt.indexOf('not OCR output')!==-1,'prompt states the text is exact, not OCR',true);
  const sn=safeName('../../evil'); check(!/[\\/]/.test(sn)&&sn!=='.'&&sn!=='..','safeName yields a harmless filename component',sn);
  console.log('\n=== WHITEBOARD MODULE: '+pass+' passed, '+fail+' failed ===   MIN_SOURCE_CHARS='+MIN_SOURCE_CHARS);
  process.exit(fail?1:0);
})();
